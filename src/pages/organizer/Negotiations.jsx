import { useEffect, useState } from 'react';
import OrganizerLayout from '../../layouts/OrganizerLayout';
import api from '../../services/api';
import { useNotification } from '../../context/NotificationContext';
import { Handshake, Bot, Check, X, ArrowRight, MessageSquare, History, Sparkles } from 'lucide-react';

export default function Negotiations() {
  const { showToast } = useNotification();
  const [proposals, setProposals] = useState([]);
  const [loading, setLoading] = useState(true);
  const [selectedProposal, setSelectedProposal] = useState(null);
  const [proposalDetail, setProposalDetail] = useState(null);
  const [aiAdvice, setAiAdvice] = useState(null);
  const [loadingAi, setLoadingAi] = useState(false);

  // Counteroffer form modal state
  const [showCounterModal, setShowCounterModal] = useState(false);
  const [counterPrice, setCounterPrice] = useState('');
  const [counterNotes, setCounterNotes] = useState('');

  // Reject modal state
  const [showRejectModal, setShowRejectModal] = useState(false);
  const [rejectionReason, setRejectionReason] = useState('');

  const loadProposals = async () => {
    try {
      setLoading(true);
      const res = await api.get('/negotiations');
      if (res.data?.success) {
        setProposals(res.data.data);
      }
    } catch (err) {
      showToast('Failed to load proposals', 'error');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadProposals();
  }, []);

  const handleSelectProposal = async (propId) => {
    try {
      setSelectedProposal(propId);
      setAiAdvice(null);
      const res = await api.get(`/negotiations/${propId}`);
      if (res.data?.success) {
        setProposalDetail(res.data.data);
        setCounterPrice(String(res.data.data.proposal?.proposed_price || ''));
      }
    } catch (err) {
      showToast('Failed to load proposal details', 'error');
    }
  };

  const handleGetAiAdvice = async (propId) => {
    try {
      setLoadingAi(true);
      const res = await api.get(`/negotiations/${propId}/ai-advice`);
      if (res.data?.success) {
        setAiAdvice(res.data.data);
        if (res.data.data.recommended_price) {
          setCounterPrice(String(res.data.data.recommended_price));
        }
        if (res.data.data.draft_counteroffer_message) {
          setCounterNotes(res.data.data.draft_counteroffer_message);
        }
        showToast('AI negotiation strategy generated by Ollama', 'success');
      }
    } catch (err) {
      showToast('Could not generate AI advice', 'error');
    } finally {
      setLoadingAi(false);
    }
  };

  const handleSendCounteroffer = async (e) => {
    e.preventDefault();
    if (!counterPrice) return showToast('Please enter a counter price', 'error');

    try {
      const res = await api.post(`/negotiations/${selectedProposal}/counteroffer`, {
        counter_price: Number(counterPrice),
        notes: counterNotes
      });
      if (res.data?.success) {
        showToast('Counteroffer sent to sponsor!', 'success');
        setShowCounterModal(false);
        handleSelectProposal(selectedProposal);
        loadProposals();
      }
    } catch (err) {
      showToast(err.response?.data?.message || 'Failed to send counteroffer', 'error');
    }
  };

  const handleAcceptProposal = async () => {
    if (!window.confirm('Accepting this proposal will lock exclusive inventory and generate a binding draft agreement. Proceed?')) return;
    try {
      const res = await api.post(`/negotiations/${selectedProposal}/accept`);
      if (res.data?.success) {
        showToast(`Proposal accepted! Agreement ${res.data.data?.agreementNumber} drafted.`, 'success');
        handleSelectProposal(selectedProposal);
        loadProposals();
      }
    } catch (err) {
      showToast(err.response?.data?.message || 'Acceptance failed', 'error');
    }
  };

  const handleRejectProposal = async (e) => {
    e.preventDefault();
    try {
      const res = await api.post(`/negotiations/${selectedProposal}/reject`, {
        rejection_reason: rejectionReason
      });
      if (res.data?.success) {
        showToast('Proposal rejected and inventory unreserved.', 'success');
        setShowRejectModal(false);
        handleSelectProposal(selectedProposal);
        loadProposals();
      }
    } catch (err) {
      showToast(err.response?.data?.message || 'Rejection failed', 'error');
    }
  };

  return (
    <OrganizerLayout title="Proposal & Negotiation Assistant" subtitle="Review incoming proposals, compare version rounds, consult local Ollama AI, and send counteroffers">
      <div className="card-grid two-up" style={{ gridTemplateColumns: '1.2fr 1.8fr' }}>
        {/* Left: Proposals Inbox */}
        <div className="panel">
          <div className="panel-header">
            <h3>Proposals Inbox ({proposals.length})</h3>
            <span>Incoming offers</span>
          </div>
          <div style={{ padding: '12px', display: 'grid', gap: '8px', maxHeight: '78vh', overflowY: 'auto' }}>
            {loading ? (
              <p style={{ textAlign: 'center', padding: '20px', color: 'var(--muted)' }}>Loading proposals...</p>
            ) : proposals.length === 0 ? (
              <p style={{ textAlign: 'center', padding: '20px', color: 'var(--muted)' }}>No proposals received yet.</p>
            ) : (
              proposals.map((p) => {
                const isSelected = selectedProposal === p.id;
                return (
                  <div
                    key={p.id}
                    onClick={() => handleSelectProposal(p.id)}
                    style={{
                      padding: '14px',
                      borderRadius: '10px',
                      border: isSelected ? '2px solid var(--violet)' : '1px solid var(--border)',
                      background: isSelected ? '#f5f3ff' : 'white',
                      cursor: 'pointer',
                      transition: 'all 0.2s'
                    }}
                  >
                    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'start', marginBottom: '6px' }}>
                      <strong style={{ fontSize: '0.95rem' }}>{p.company_name}</strong>
                      <span className={`badge ${
                        p.status === 'accepted' ? 'badge-success' : p.status === 'rejected' ? 'badge-neutral' : 'badge-warning'
                      }`}>
                        {p.status.replace(/_/g, ' ')}
                      </span>
                    </div>

                    <div style={{ fontSize: '0.85rem', color: 'var(--muted)' }}>
                      Event: {p.event_name}
                    </div>

                    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginTop: '10px' }}>
                      <div>
                        <span style={{ fontSize: '0.75rem', color: 'var(--muted)' }}>Offer (v{p.current_version}):</span>
                        <strong style={{ display: 'block', color: 'var(--violet)' }}>
                          ₹{Number(p.proposed_price).toLocaleString()}
                        </strong>
                      </div>
                      <div style={{ textAlign: 'right' }}>
                        <span style={{ fontSize: '0.75rem', color: 'var(--muted)' }}>Est. Contribution:</span>
                        <strong style={{ display: 'block', color: '#10b981' }}>
                          ₹{Number(p.estimated_contribution).toLocaleString()} ({p.contribution_margin}%)
                        </strong>
                      </div>
                    </div>
                  </div>
                );
              })
            )}
          </div>
        </div>

        {/* Right: Proposal Negotiation Room */}
        <div className="panel">
          {!proposalDetail ? (
            <div style={{ padding: '60px 20px', textAlign: 'center', color: 'var(--muted)' }}>
              <Handshake size={48} color="#cbd5e1" style={{ margin: '0 auto 12px' }} />
              <h3>Select a Proposal from the Inbox</h3>
              <p>Review offer terms, inspect negotiation rounds, and send counteroffers.</p>
            </div>
          ) : (
            <div>
              {/* Proposal Header */}
              <div className="panel-header">
                <div>
                  <h3 style={{ margin: 0 }}>{proposalDetail.proposal?.title}</h3>
                  <small style={{ color: 'var(--muted)' }}>
                    From: {proposalDetail.proposal?.company_name} ({proposalDetail.proposal?.contact_email})
                  </small>
                </div>

                <div style={{ display: 'flex', gap: '8px' }}>
                  {proposalDetail.proposal?.status !== 'accepted' && proposalDetail.proposal?.status !== 'rejected' && (
                    <>
                      <button
                        className="action-btn-sm"
                        onClick={() => handleGetAiAdvice(proposalDetail.proposal.id)}
                        disabled={loadingAi}
                        style={{ display: 'flex', alignItems: 'center', gap: '6px', color: 'var(--violet)' }}
                      >
                        <Bot size={14} /> {loadingAi ? 'Thinking...' : 'AI Strategy'}
                      </button>
                      <button
                        className="action-btn-sm"
                        onClick={() => setShowCounterModal(true)}
                      >
                        Counteroffer
                      </button>
                      <button
                        className="action-btn-sm primary"
                        onClick={handleAcceptProposal}
                      >
                        <Check size={14} style={{ marginRight: '4px' }} /> Accept Deal
                      </button>
                      <button
                        className="action-btn-sm danger"
                        onClick={() => setShowRejectModal(true)}
                      >
                        <X size={14} />
                      </button>
                    </>
                  )}
                </div>
              </div>

              <div style={{ padding: '20px', display: 'grid', gap: '18px' }}>
                {/* Financial Summary */}
                <div style={{ display: 'grid', gridTemplateColumns: 'repeat(4, 1fr)', gap: '10px' }}>
                  <div style={{ background: '#f8fafc', padding: '10px', borderRadius: '8px' }}>
                    <span style={{ fontSize: '0.75rem', color: 'var(--muted)' }}>Current Price</span>
                    <strong style={{ display: 'block', fontSize: '1.1rem', color: 'var(--violet)' }}>
                      ₹{Number(proposalDetail.proposal?.proposed_price).toLocaleString()}
                    </strong>
                  </div>
                  <div style={{ background: '#f8fafc', padding: '10px', borderRadius: '8px' }}>
                    <span style={{ fontSize: '0.75rem', color: 'var(--muted)' }}>Fulfilment Cost</span>
                    <strong style={{ display: 'block', fontSize: '1.1rem' }}>
                      ₹{Number(proposalDetail.proposal?.estimated_fulfilment_cost).toLocaleString()}
                    </strong>
                  </div>
                  <div style={{ background: '#f8fafc', padding: '10px', borderRadius: '8px' }}>
                    <span style={{ fontSize: '0.75rem', color: 'var(--muted)' }}>Contribution</span>
                    <strong style={{ display: 'block', fontSize: '1.1rem', color: '#10b981' }}>
                      ₹{Number(proposalDetail.proposal?.estimated_contribution).toLocaleString()}
                    </strong>
                  </div>
                  <div style={{ background: '#f8fafc', padding: '10px', borderRadius: '8px' }}>
                    <span style={{ fontSize: '0.75rem', color: 'var(--muted)' }}>Margin</span>
                    <strong style={{ display: 'block', fontSize: '1.1rem', color: '#10b981' }}>
                      {proposalDetail.proposal?.contribution_margin}%
                    </strong>
                  </div>
                </div>

                {/* AI Advice Callout */}
                {aiAdvice && (
                  <div style={{ background: '#faf5ff', border: '1px solid #c084fc', borderRadius: '10px', padding: '16px' }}>
                    <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '8px' }}>
                      <Sparkles size={16} color="#7c3aed" />
                      <strong style={{ color: '#581c87', fontSize: '0.9rem' }}>
                        Local Ollama AI Tactical Recommendation:
                      </strong>
                    </div>
                    <p style={{ margin: '0 0 10px', fontSize: '0.88rem', color: '#3b0764' }}>
                      {aiAdvice.strategy_summary}
                    </p>
                    <div style={{ fontSize: '0.82rem', color: '#6b21a8' }}>
                      <strong>Suggested Price:</strong> ₹{Number(aiAdvice.recommended_price).toLocaleString()} • <strong>Sweeteners:</strong> {(aiAdvice.sweetener_benefits || []).join(', ')}
                    </div>
                    {aiAdvice.draft_counteroffer_message && (
                      <div style={{ marginTop: '10px', background: 'white', padding: '10px', borderRadius: '6px', fontSize: '0.82rem', border: '1px solid #e9d5ff' }}>
                        <em>"{aiAdvice.draft_counteroffer_message}"</em>
                      </div>
                    )}
                  </div>
                )}

                {/* Negotiation Rounds Timeline */}
                <div>
                  <h4 style={{ margin: '0 0 10px', display: 'flex', alignItems: 'center', gap: '6px' }}>
                    <History size={16} /> Negotiation Version History ({proposalDetail.versions?.length || 0} rounds)
                  </h4>
                  <div style={{ display: 'grid', gap: '10px' }}>
                    {(proposalDetail.versions || []).map((v) => (
                      <div key={v.id} style={{ border: '1px solid var(--border)', borderRadius: '8px', padding: '12px' }}>
                        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '6px' }}>
                          <div>
                            <strong>Round Version {v.version_number}</strong>
                            <span className="tag-chip" style={{ marginLeft: '8px' }}>
                              Offered by {v.proposed_by_role} ({v.proposed_by_name})
                            </span>
                          </div>
                          <strong style={{ color: 'var(--violet)' }}>₹{Number(v.proposed_price).toLocaleString()}</strong>
                        </div>
                        {v.notes && (
                          <p style={{ margin: '4px 0 0', fontSize: '0.85rem', color: '#475569' }}>
                            "{v.notes}"
                          </p>
                        )}
                      </div>
                    ))}
                  </div>
                </div>

                {/* Negotiation Audit Log */}
                <div>
                  <h4 style={{ margin: '0 0 10px', display: 'flex', alignItems: 'center', gap: '6px' }}>
                    <MessageSquare size={16} /> Audit Timeline
                  </h4>
                  <div style={{ display: 'grid', gap: '8px' }}>
                    {(proposalDetail.history || []).map((h) => (
                      <div key={h.id} style={{ fontSize: '0.82rem', padding: '8px 12px', background: '#f8fafc', borderRadius: '6px', display: 'flex', justifyContent: 'space-between' }}>
                        <span>
                          <strong>{h.action_by_name}</strong>: {h.message}
                        </span>
                        <span style={{ color: 'var(--muted)' }}>
                          {new Date(h.created_at).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                        </span>
                      </div>
                    ))}
                  </div>
                </div>
              </div>
            </div>
          )}
        </div>
      </div>

      {/* Counteroffer Modal */}
      {showCounterModal && (
        <div className="modal-overlay">
          <div className="modal-card">
            <div className="modal-header">
              <h3 style={{ margin: 0 }}>Draft Counteroffer</h3>
              <button className="toolbar-button" onClick={() => setShowCounterModal(false)}>×</button>
            </div>
            <form onSubmit={handleSendCounteroffer}>
              <div className="modal-body" style={{ display: 'grid', gap: '12px' }}>
                <label style={{ display: 'grid', gap: '4px', fontWeight: 600, fontSize: '0.85rem' }}>
                  Counter Proposed Price (₹) *
                  <input
                    type="number"
                    required
                    min={1}
                    className="filter-input"
                    value={counterPrice}
                    onChange={(e) => setCounterPrice(e.target.value)}
                  />
                </label>

                <label style={{ display: 'grid', gap: '4px', fontWeight: 600, fontSize: '0.85rem' }}>
                  Negotiation Note / Commercial Rationale
                  <textarea
                    rows={3}
                    className="filter-input"
                    placeholder="Explain the revised pricing, included value add-ons, or payment schedule..."
                    value={counterNotes}
                    onChange={(e) => setCounterNotes(e.target.value)}
                  />
                </label>

                <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '10px', marginTop: '10px' }}>
                  <button type="button" className="ghost-button" onClick={() => setShowCounterModal(false)}>Cancel</button>
                  <button type="submit" className="primary-button">Send Counteroffer</button>
                </div>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* Reject Modal */}
      {showRejectModal && (
        <div className="modal-overlay">
          <div className="modal-card">
            <div className="modal-header">
              <h3 style={{ margin: 0, color: '#ef4444' }}>Reject Proposal</h3>
              <button className="toolbar-button" onClick={() => setShowRejectModal(false)}>×</button>
            </div>
            <form onSubmit={handleRejectProposal}>
              <div className="modal-body" style={{ display: 'grid', gap: '12px' }}>
                <label style={{ display: 'grid', gap: '4px', fontWeight: 600, fontSize: '0.85rem' }}>
                  Rejection Reason *
                  <textarea
                    rows={3}
                    required
                    className="filter-input"
                    placeholder="State reason: e.g. Price too low, inventory committed, category conflict..."
                    value={rejectionReason}
                    onChange={(e) => setRejectionReason(e.target.value)}
                  />
                </label>

                <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '10px', marginTop: '10px' }}>
                  <button type="button" className="ghost-button" onClick={() => setShowRejectModal(false)}>Cancel</button>
                  <button type="submit" className="action-btn-sm danger" style={{ padding: '8px 16px' }}>Confirm Rejection</button>
                </div>
              </div>
            </form>
          </div>
        </div>
      )}
    </OrganizerLayout>
  );
}
